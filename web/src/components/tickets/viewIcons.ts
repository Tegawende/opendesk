const byName = new Map(VIEW_ICONS.map((d) => [d.name, d]));

/** The allowlisted icon of that name, or undefined. */
export const viewIconDef = (name: string): ViewIconDef | undefined => byName.get(name);

/** Icons whose name or words start with each word of the query. */
export function searchViewIcons(q: string): ViewIconDef[] {
  const terms = q.toLowerCase().split(/\s+/).filter(Boolean);
  if (!terms.length) return VIEW_ICONS;
  return VIEW_ICONS.filter((d) => {
    const words = `${d.name.replace(/-/g, " ")} ${d.words}`.split(" ");
    return terms.every((t) => words.some((w) => w.startsWith(t)));
  });
}
